import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const licensingRoot = join(projectRoot, "docs", "licensing");
const outputFile = join(projectRoot, "src", "config", "licensingDocs.generated.ts");

const topLevelOrder = [
  ["README.md", "overview"],
  ["STATEWIDE-SOURCES.md", "statewide"],
  ["COUNTIES.md", "counties"],
  ["MONETIZATION.md", "monetization"],
  ["ATTRIBUTION.md", "attribution"],
  ["RISK-REGISTER.md", "risk"],
  ["QUESTIONS-FOR-AGENCIES.md", "questions"],
];

async function readIfExists(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

function titleFromMarkdown(content, fallback) {
  const match = content.match(/^#\s+(.+)$/m);
  return match ? match[1].trim() : fallback;
}

function slugify(value) {
  return value.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-").replaceAll(/(^-|-$)/g, "");
}

const docs = [];

for (const [filename, category] of topLevelOrder) {
  const content = await readIfExists(join(licensingRoot, filename));
  if (content == null) continue;
  const slug = slugify(filename.replace(/\.md$/, ""));
  docs.push({ slug, title: titleFromMarkdown(content, filename), category, content });
}

const detailsDir = join(licensingRoot, "COUNTY-DETAILS");
let detailFiles = [];
try {
  detailFiles = (await readdir(detailsDir)).filter((name) => name.endsWith(".md")).sort();
} catch {
  detailFiles = [];
}

for (const filename of detailFiles) {
  const content = await readFile(join(detailsDir, filename), "utf8");
  const slug = `county-detail-${slugify(filename.replace(/\.md$/, ""))}`;
  docs.push({ slug, title: titleFromMarkdown(content, filename.replace(/\.md$/, "")), category: "county-detail", content });
}

const banner = "// Generated by scripts/generate-licensing-docs.mjs from docs/licensing/. Do not edit by hand.\n";
const body = `${banner}export interface LicensingDoc {\n  slug: string;\n  title: string;\n  category: "overview" | "statewide" | "counties" | "monetization" | "attribution" | "risk" | "questions" | "county-detail";\n  content: string;\n}\n\nexport const licensingDocs: readonly LicensingDoc[] = ${JSON.stringify(docs, null, 2)} as const;\n`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(outputFile, body);
console.log(`Wrote ${docs.length} licensing doc(s) to ${outputFile}`);
